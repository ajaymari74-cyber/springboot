package com.example.studentmanagement.dto;

public class StaffDTO {


private Long id;
private String name;
private long phono;

public StaffDTO() {
	
}

public Long getId() {
	return id;
}
public void setId(Long id) {
	this.id = id;
}
public String getName() {
	return name;
}
public void setName(String name) {
	this.name = name;
}
public long getPhono() {
	return phono;
}
public void setPhono(long phono) {
	this.phono = phono;
}

}

